# ==========================================
# PROJETO: MONITORAMENTO AMBIENTAL
# Ambiente escolhido: Sala de aula
# ==========================================

print("====================================")
print("     MONITORAMENTO AMBIENTAL")
print("====================================")

# Limites de referencia
TEMP_MIN = 21
TEMP_MAX = 26

LUZ_MIN = 300
LUZ_MAX = 500

RUIDO_MAX = 35

# Funcao para calcular estatisticas
def calcular_estatisticas(lista):
    media = sum(lista) / len(lista)
    maior = max(lista)
    menor = min(lista)

    return media, maior, menor


# Inicio do programa
while True:

    # Listas para armazenar os dados
    temperaturas = []
    luminosidades = []
    ruidos = []

    # Contadores de alertas
    alertas_temperatura = 0
    alertas_luminosidade = 0
    alertas_ruido = 0
    leituras_criticas = 0

    print("\nAmbiente: Sala de aula")

    print("\nLimites utilizados:")
    print(f"Temperatura: {TEMP_MIN} a {TEMP_MAX} °C")
    print(f"Luminosidade: {LUZ_MIN} a {LUZ_MAX} lux")
    print(f"Ruido maximo: {RUIDO_MAX} dB(A)")

    # Solicita a quantidade de leituras
    quantidade = int(input("\nQuantas leituras deseja realizar? "))

    while quantidade <= 0:
        print("Digite uma quantidade maior que zero.")
        quantidade = int(input("Quantas leituras deseja realizar? "))

    # Coleta e analise dos dados
    for i in range(quantidade):

        print(f"\n--- Leitura {i + 1} ---")

        temperatura = float(input("Temperatura (°C): "))
        luminosidade = float(input("Luminosidade (lux): "))
        ruido = float(input("Ruido (dB): "))

        # Armazena os valores
        temperaturas.append(temperatura)
        luminosidades.append(luminosidade)
        ruidos.append(ruido)

        critica = False

        # Verifica temperatura
        if temperatura < TEMP_MIN or temperatura > TEMP_MAX:
            print("ALERTA: Temperatura fora dos limites!")
            alertas_temperatura += 1
            critica = True

        # Verifica luminosidade
        if luminosidade < LUZ_MIN or luminosidade > LUZ_MAX:
            print("ALERTA: Luminosidade fora dos limites!")
            alertas_luminosidade += 1
            critica = True

        # Verifica ruido
        if ruido > RUIDO_MAX:
            print("ALERTA: Ruido acima do limite!")
            alertas_ruido += 1
            critica = True

        # Conta leituras criticas
        if critica:
            leituras_criticas += 1
        else:
            print("Leitura dentro dos limites!")

    # Calcula as estatisticas
    media_temp, maior_temp, menor_temp = calcular_estatisticas(temperaturas)
    media_luz, maior_luz, menor_luz = calcular_estatisticas(luminosidades)
    media_ruido, maior_ruido, menor_ruido = calcular_estatisticas(ruidos)

    # Calcula a porcentagem de leituras criticas
    porcentagem_critica = (leituras_criticas / quantidade) * 100

    # Exibe as estatisticas
    print("\n========== ESTATISTICAS ==========")

    print("\nTEMPERATURA")
    print(f"Media: {media_temp:.2f} °C")
    print(f"Maior valor: {maior_temp} °C")
    print(f"Menor valor: {menor_temp} °C")

    print("\nLUMINOSIDADE")
    print(f"Media: {media_luz:.2f} lux")
    print(f"Maior valor: {maior_luz} lux")
    print(f"Menor valor: {menor_luz} lux")

    print("\nRUIDO")
    print(f"Media aritmetica: {media_ruido:.2f} dB")
    print(f"Maior valor: {maior_ruido} dB")
    print(f"Menor valor: {menor_ruido} dB")

    # Exibe os alertas
    print("\n========== ALERTAS ==========")
    print("Alertas de temperatura:", alertas_temperatura)
    print("Alertas de luminosidade:", alertas_luminosidade)
    print("Alertas de ruido:", alertas_ruido)
    print("Total de leituras criticas:", leituras_criticas)

    # Classificacao geral
    print("\n========== CLASSIFICACAO GERAL ==========")
    print("Leituras criticas:", leituras_criticas)
    print("Total de leituras:", quantidade)
    print(f"Porcentagem critica: {porcentagem_critica:.2f}%")

    if porcentagem_critica > 30:
        classificacao = "Condicoes ambientais de atencao."
    else:
        classificacao = "Frequencia de ocorrencias dentro do criterio estabelecido."

    print("Estado geral:", classificacao)

    # Cria o relatorio em arquivo TXT
    with open("relatorio_monitoramento.txt", "w", encoding="utf-8") as arquivo:

        arquivo.write("RELATORIO DE MONITORAMENTO AMBIENTAL\n")
        arquivo.write("Ambiente: Sala de aula\n\n")

        arquivo.write("LIMITES DE REFERENCIA\n")
        arquivo.write(f"Temperatura: {TEMP_MIN} a {TEMP_MAX} °C\n")
        arquivo.write(f"Luminosidade: {LUZ_MIN} a {LUZ_MAX} lux\n")
        arquivo.write(f"Ruido maximo: {RUIDO_MAX} dB(A)\n\n")

        arquivo.write("LEITURAS REGISTRADAS\n")

        for i in range(quantidade):
            arquivo.write(f"\nLeitura {i + 1}:\n")
            arquivo.write(f"Temperatura: {temperaturas[i]} °C\n")
            arquivo.write(f"Luminosidade: {luminosidades[i]} lux\n")
            arquivo.write(f"Ruido: {ruidos[i]} dB\n")

        arquivo.write("\nESTATISTICAS\n")
        arquivo.write(f"Temperatura - Media: {media_temp:.2f} °C\n")
        arquivo.write(f"Temperatura - Maior: {maior_temp} °C\n")
        arquivo.write(f"Temperatura - Menor: {menor_temp} °C\n\n")

        arquivo.write(f"Luminosidade - Media: {media_luz:.2f} lux\n")
        arquivo.write(f"Luminosidade - Maior: {maior_luz} lux\n")
        arquivo.write(f"Luminosidade - Menor: {menor_luz} lux\n\n")

        arquivo.write(f"Ruido - Media aritmetica: {media_ruido:.2f} dB\n")
        arquivo.write(f"Ruido - Maior: {maior_ruido} dB\n")
        arquivo.write(f"Ruido - Menor: {menor_ruido} dB\n\n")

        arquivo.write("ALERTAS\n")
        arquivo.write(f"Alertas de temperatura: {alertas_temperatura}\n")
        arquivo.write(f"Alertas de luminosidade: {alertas_luminosidade}\n")
        arquivo.write(f"Alertas de ruido: {alertas_ruido}\n\n")

        arquivo.write(f"Leituras criticas: {leituras_criticas}\n")
        arquivo.write(f"Total de leituras: {quantidade}\n")
        arquivo.write(f"Porcentagem critica: {porcentagem_critica:.2f}%\n\n")

        arquivo.write("CLASSIFICACAO GERAL\n")
        arquivo.write(classificacao + "\n")

        arquivo.write(
            "\nObservacao: a media de ruido e uma media aritmetica "
            "simples, utilizada apenas como estatistica descritiva.\n"
        )

    print("\nRelatorio salvo com sucesso!")

    # Pergunta se deseja realizar outra sequencia
    resposta = input("\nDeseja realizar uma nova analise? (s/n): ")

    if resposta.lower() != "s":
        print("\nPrograma encerrado. Obrigado!")
        break
